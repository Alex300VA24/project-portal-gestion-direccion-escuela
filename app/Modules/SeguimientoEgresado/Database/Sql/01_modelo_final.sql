-- Integridad transversal sin repetir id_plan_curricular en las evaluaciones.
CREATE OR REPLACE FUNCTION fn_validar_plan_evaluacion() RETURNS TRIGGER AS $$
DECLARE plan_obj BIGINT; plan_coh BIGINT;
BEGIN
    IF TG_TABLE_NAME = 'evaluacion_oe' THEN
        SELECT id_plan_curricular INTO plan_obj FROM objetivo_educacional WHERE id = NEW.id_objetivo;
    ELSE
        SELECT id_plan_curricular INTO plan_obj FROM competencia WHERE id = NEW.id_competencia;
    END IF;
    SELECT id_plan_curricular INTO plan_coh FROM cohorte WHERE id = NEW.id_cohorte;
    IF plan_coh IS NULL OR plan_obj IS DISTINCT FROM plan_coh THEN
        RAISE EXCEPTION 'La cohorte y el objetivo o competencia deben pertenecer al mismo plan';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg_evaluacion_oe_plan BEFORE INSERT OR UPDATE ON evaluacion_oe
    FOR EACH ROW EXECUTE FUNCTION fn_validar_plan_evaluacion();
CREATE TRIGGER trg_evaluacion_competencia_plan BEFORE INSERT OR UPDATE ON evaluacion_competencia
    FOR EACH ROW EXECUTE FUNCTION fn_validar_plan_evaluacion();

CREATE OR REPLACE FUNCTION fn_bloquear_cambio_plan() RETURNS TRIGGER AS $$
BEGIN
    IF OLD.id_plan_curricular IS DISTINCT FROM NEW.id_plan_curricular THEN
        IF TG_TABLE_NAME = 'cohorte' AND
            (EXISTS (SELECT 1 FROM evaluacion_oe WHERE id_cohorte = OLD.id)
             OR EXISTS (SELECT 1 FROM evaluacion_competencia WHERE id_cohorte = OLD.id)) THEN
            RAISE EXCEPTION 'No se puede cambiar el plan de una cohorte ya evaluada';
        ELSIF TG_TABLE_NAME = 'objetivo_educacional' AND
            EXISTS (SELECT 1 FROM evaluacion_oe WHERE id_objetivo = OLD.id) THEN
            RAISE EXCEPTION 'No se puede cambiar el plan de un OE evaluado';
        ELSIF TG_TABLE_NAME = 'competencia' AND
            EXISTS (SELECT 1 FROM evaluacion_competencia WHERE id_competencia = OLD.id) THEN
            RAISE EXCEPTION 'No se puede cambiar el plan de una competencia evaluada';
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg_cohorte_plan_inmutable BEFORE UPDATE ON cohorte
    FOR EACH ROW EXECUTE FUNCTION fn_bloquear_cambio_plan();
CREATE TRIGGER trg_oe_plan_inmutable BEFORE UPDATE ON objetivo_educacional
    FOR EACH ROW EXECUTE FUNCTION fn_bloquear_cambio_plan();
CREATE TRIGGER trg_competencia_plan_inmutable BEFORE UPDATE ON competencia
    FOR EACH ROW EXECUTE FUNCTION fn_bloquear_cambio_plan();

-- Las respuestas de mercado no pueden guardar valoraciones de desempeño (I5).
CREATE OR REPLACE FUNCTION fn_validar_respuesta_empresa() RETURNS TRIGGER AS $$
DECLARE contexto_encuesta VARCHAR(20);
BEGIN
    SELECT contexto INTO contexto_encuesta FROM invitacion_empresa WHERE id = NEW.id_invitacion_empresa;
    IF contexto_encuesta = 'MERCADO' AND NEW.id_nivel_satisfaccion IS NOT NULL THEN
        RAISE EXCEPTION 'Las encuestas de mercado no pueden contener satisfacción de desempeño';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg_respuesta_empresa_contexto BEFORE INSERT OR UPDATE ON respuesta_empresa
    FOR EACH ROW EXECUTE FUNCTION fn_validar_respuesta_empresa();

-- Una medición debe proceder de una invitación de seguimiento, nunca del contacto inicial.
CREATE OR REPLACE FUNCTION fn_validar_medicion() RETURNS TRIGGER AS $$
DECLARE proposito_invitacion VARCHAR(20);
BEGIN
    SELECT proposito INTO proposito_invitacion FROM invitacion_egresado WHERE id = NEW.id_invitacion;
    IF proposito_invitacion <> 'SEGUIMIENTO' THEN
        RAISE EXCEPTION 'Solo una invitación de seguimiento puede producir una medición laboral';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg_medicion_invitacion BEFORE INSERT OR UPDATE ON medicion_laboral
    FOR EACH ROW EXECUTE FUNCTION fn_validar_medicion();


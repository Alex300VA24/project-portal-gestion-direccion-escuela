-- cohorte | Cohorte de ingresantes y denominador oficial de I1
CREATE TABLE cohorte (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    codigo_promocion VARCHAR(40) NOT NULL,
    anio_ingreso INTEGER NOT NULL,
    semestre_ingreso VARCHAR(2),
    total_ingresantes INTEGER NOT NULL,
    duracion_esperada_anios SMALLINT,
    id_plan_curricular BIGINT,
    observacion TEXT,
    PRIMARY KEY (id),
    FOREIGN KEY (id_plan_curricular) REFERENCES plan_curricular(id),
    UNIQUE (codigo_promocion, anio_ingreso),
    CHECK (anio_ingreso BETWEEN 1950 AND 2100),
    CHECK (semestre_ingreso IS NULL OR semestre_ingreso IN ('I','II')),
    CHECK (total_ingresantes >= 0),
    CHECK (duracion_esperada_anios IS NULL OR duracion_esperada_anios > 0)
);

-- competencia | Competencias generales y específicas por versión curricular
CREATE TABLE competencia (

-- contacto_egresado | Versiones fechadas de contacto: una vigente por persona
CREATE TABLE contacto_egresado (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_egresado BIGINT NOT NULL,
    correo_personal VARCHAR(254) NOT NULL,
    celular_whatsapp VARCHAR(25) NOT NULL,
    telefono_fijo VARCHAR(25),
    direccion VARCHAR(250),
    vigente_desde TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    vigente_hasta TIMESTAMPTZ,

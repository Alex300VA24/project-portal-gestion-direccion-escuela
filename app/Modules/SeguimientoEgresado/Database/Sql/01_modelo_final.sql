    tipo VARCHAR(12) NOT NULL,
    descripcion TEXT NOT NULL,
    nivel_esperado VARCHAR(30),
    vigente BOOLEAN NOT NULL,
    PRIMARY KEY (id),
    FOREIGN KEY (id_plan_curricular) REFERENCES plan_curricular(id),
    UNIQUE (id_plan_curricular, codigo),
    CHECK (tipo IN ('GENERAL','ESPECIFICA'))
);


-- auditoria | Traza de cambios administrativos, OE, mejoras y reportes
CREATE TABLE auditoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_usuario BIGINT NOT NULL,
    tabla_afectada VARCHAR(90) NOT NULL,
    id_registro BIGINT,
    accion VARCHAR(30) NOT NULL,
    detalle JSONB NOT NULL,
    registrado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    FOREIGN KEY (id_usuario) REFERENCES usuario_interno(id)
);

-- campania_seguimiento | Campañas de seguimiento y/o encuestas empresariales
CREATE TABLE campania_seguimiento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre VARCHAR(160) NOT NULL,
    tipo VARCHAR(15) NOT NULL,
    finalidad VARCHAR(25) NOT NULL DEFAULT 'SEGUIMIENTO',
    horizonte_anios SMALLINT,
    descripcion TEXT,
    periodo VARCHAR(35) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    estado VARCHAR(20) NOT NULL,
    id_usuario_creacion BIGINT NOT NULL,
    PRIMARY KEY (id),
    FOREIGN KEY (id_usuario_creacion) REFERENCES usuario_interno(id),
    CHECK (fecha_fin >= fecha_inicio),
    CHECK (tipo IN ('EGRESADOS','EMPRESAS','MIXTA')),
    CHECK (estado IN ('BORRADOR','PROGRAMADA','ABIERTA','CERRADA')),
    CHECK (finalidad IN ('SEGUIMIENTO','DIAGNOSTICO_TEMPRANO','EVALUACION_INSTITUCIONAL','EXTRAORDINARIA')),
    CHECK (horizonte_anios IS NULL OR horizonte_anios IN (1,3,5,10))
);

-- egresado | Expediente de persona único antes y después del egreso
CREATE TABLE egresado (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_cohorte BIGINT NOT NULL,
    codigo_matricula VARCHAR(35) NOT NULL UNIQUE,
    tipo_documento VARCHAR(15),
    numero_documento VARCHAR(25),
    nombres VARCHAR(110) NOT NULL,
    apellido_paterno VARCHAR(70) NOT NULL,
    apellido_materno VARCHAR(70),
    programa VARCHAR(120) NOT NULL,
    correo_institucional VARCHAR(254),
    sede VARCHAR(100),
    fecha_ingreso DATE,
    fecha_egreso DATE,
    periodo_egreso VARCHAR(20),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    FOREIGN KEY (id_cohorte) REFERENCES cohorte(id),
    UNIQUE (tipo_documento, numero_documento),
    CHECK ((tipo_documento IS NULL) = (numero_documento IS NULL)),
    CHECK (fecha_egreso IS NULL OR fecha_ingreso IS NULL OR fecha_egreso >= fecha_ingreso)
);

-- importacion_padron | Registro de importaciones manuales o archivos que cargó Secretaría
CREATE TABLE importacion_padron (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_usuario BIGINT NOT NULL,
    nombre_archivo VARCHAR(250),
    hash_archivo CHAR(64),
    origen VARCHAR(20) NOT NULL,
    fecha_importacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado VARCHAR(20) NOT NULL,
    PRIMARY KEY (id),
    FOREIGN KEY (id_usuario) REFERENCES usuario_interno(id),
    CHECK (origen IN ('MANUAL','ARCHIVO')),
    CHECK (estado IN ('EN_PROCESO','VALIDADA','CON_ERRORES'))
);

-- reporte_generado | Bitácora de documentos I1-I6 y F1-F11; fuente temporal congelada
CREATE TABLE reporte_generado (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    tipo VARCHAR(25) NOT NULL,
    codigo_formato VARCHAR(8),
    periodo_inicio DATE,
    periodo_fin DATE,
    fecha_corte TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    generado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    filtros JSONB NOT NULL DEFAULT '{}'::jsonb,
    ruta_archivo TEXT,
    sha256_archivo CHAR(64),
    id_usuario BIGINT NOT NULL,
    PRIMARY KEY (id),
    FOREIGN KEY (id_usuario) REFERENCES usuario_interno(id),
    CHECK (tipo IN ('INDICADOR','CONSOLIDADO','FORMATO')),
    CHECK ((tipo = 'FORMATO') = (codigo_formato IS NOT NULL)),
    CHECK (codigo_formato IS NULL OR codigo_formato IN ('F1','F2','F3','F4','F5','F6','F7','F8','F9','F10','F11')),
    CHECK (periodo_fin IS NULL OR periodo_inicio IS NULL OR periodo_fin >= periodo_inicio)
);

-- campania_cohorte | Tabla puente para filtrar varias cohortes por campaña
CREATE TABLE campania_cohorte (

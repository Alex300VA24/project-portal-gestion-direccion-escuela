-- archivo_evidencia | Repositorio lógico de evidencias institucionales
CREATE TABLE archivo_evidencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre_original VARCHAR(250) NOT NULL,
    ruta_repositorio TEXT NOT NULL,
    sha256 CHAR(64) NOT NULL,
    mime VARCHAR(120) NOT NULL,
    registrado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_usuario BIGINT NOT NULL,
    PRIMARY KEY (id),
    FOREIGN KEY (id_usuario) REFERENCES usuario_interno(id)

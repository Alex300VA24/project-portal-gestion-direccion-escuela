-- evaluacion_competencia | Evaluación institucional de competencias por cohorte
CREATE TABLE evaluacion_competencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_competencia BIGINT NOT NULL,
    id_cohorte BIGINT NOT NULL,
    periodo VARCHAR(35) NOT NULL,
    id_nivel_logro BIGINT NOT NULL,
    estado VARCHAR(15) NOT NULL,
    logro_porcentaje NUMERIC(5,2),
    observacion TEXT,
    fuente_evidencia TEXT,
    id_evidencia BIGINT,
    fecha_evaluacion DATE NOT NULL,
    id_usuario_registro BIGINT NOT NULL,
    PRIMARY KEY (id),
    FOREIGN KEY (id_competencia) REFERENCES competencia(id),
    FOREIGN KEY (id_cohorte) REFERENCES cohorte(id),
    FOREIGN KEY (id_nivel_logro) REFERENCES cat_nivel_logro(id),
    FOREIGN KEY (id_evidencia) REFERENCES archivo_evidencia(id),
    FOREIGN KEY (id_usuario_registro) REFERENCES usuario_interno(id),
    UNIQUE (id_competencia, id_cohorte, periodo),
    CHECK (estado IN ('BORRADOR','VALIDADA')),
    CHECK (logro_porcentaje IS NULL OR logro_porcentaje BETWEEN 0 AND 100)
);

-- evaluacion_oe | Resultado oficial validado por Director, por OE, cohorte y periodo
CREATE TABLE evaluacion_oe (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_objetivo BIGINT NOT NULL,
    id_cohorte BIGINT NOT NULL,
    periodo VARCHAR(35) NOT NULL,
    id_nivel_logro BIGINT NOT NULL,
    estado VARCHAR(15) NOT NULL,
    meta_porcentaje NUMERIC(5,2),
    logro_porcentaje NUMERIC(5,2),
    observacion TEXT,
    fuente_evidencia TEXT,
    acciones_derivadas TEXT,
    id_evidencia BIGINT,
    fecha_evaluacion DATE NOT NULL,
    id_usuario_registro BIGINT NOT NULL,
    PRIMARY KEY (id),
    FOREIGN KEY (id_objetivo) REFERENCES objetivo_educacional(id),

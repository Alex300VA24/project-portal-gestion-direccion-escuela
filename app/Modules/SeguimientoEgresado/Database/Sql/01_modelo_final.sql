-- invitacion_egresado | Token de contacto inicial o seguimiento posterior (sin cuenta extra)
CREATE TABLE invitacion_egresado (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_campania BIGINT,
    id_egresado BIGINT NOT NULL,
    proposito VARCHAR(20) NOT NULL,
    token_hash CHAR(64) NOT NULL UNIQUE,
    expira_en TIMESTAMPTZ NOT NULL,
    id_canal_envio BIGINT,
    enviado_en TIMESTAMPTZ,
    recordatorios_enviados SMALLINT NOT NULL DEFAULT 0,
    ultimo_recordatorio_en TIMESTAMPTZ,
    entrega_fallida BOOLEAN NOT NULL DEFAULT FALSE,
    respondido_en TIMESTAMPTZ,
    estado VARCHAR(20) NOT NULL,
    PRIMARY KEY (id),
    FOREIGN KEY (id_campania) REFERENCES campania_seguimiento(id),
    FOREIGN KEY (id_egresado) REFERENCES egresado(id),
    FOREIGN KEY (id_canal_envio) REFERENCES cat_canal_envio(id),
    CHECK ((proposito = 'CONTACTO_INICIAL' AND id_campania IS NULL) OR (proposito = 'SEGUIMIENTO' AND id_campania IS NOT NULL)),
    CHECK (estado IN ('PENDIENTE','COMPLETADA','EXPIRADA','ANULADA')),
    CHECK (recordatorios_enviados >= 0)
);

-- invitacion_empresa | Enlace externo sin cuenta; evaluación general o de desempeño
CREATE TABLE invitacion_empresa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_campania BIGINT NOT NULL,
    id_egresado BIGINT,
    contexto VARCHAR(20) NOT NULL,
    organizacion VARCHAR(180),
    contacto_empresa VARCHAR(180),

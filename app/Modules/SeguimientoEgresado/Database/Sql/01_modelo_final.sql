    CHECK (estado IN ('PENDIENTE','COMPLETADA','EXPIRADA','ANULADA'))
);

-- mejora_curricular | Mejora curricular atribuible o no al seguimiento; I6 solo implementadas
CREATE TABLE mejora_curricular (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    codigo VARCHAR(30) NOT NULL UNIQUE,
    id_plan_curricular BIGINT NOT NULL,
    titulo VARCHAR(200) NOT NULL,
    tipo VARCHAR(18) NOT NULL,
    origen_seguimiento BOOLEAN NOT NULL,
    descripcion TEXT NOT NULL,
    estado VARCHAR(20) NOT NULL,
    dice TEXT,
    debe_decir TEXT,
    fecha_registro DATE NOT NULL,
    fecha_implementacion DATE,
    periodo VARCHAR(35),
    responsable VARCHAR(160),
    meta_esperada TEXT,
    origen_evidencia TEXT,
    grado_cumplimiento NUMERIC(5,2),
    documento_referencia VARCHAR(200),
    id_evidencia BIGINT,
    id_usuario_registro BIGINT NOT NULL,
    PRIMARY KEY (id),
    FOREIGN KEY (id_plan_curricular) REFERENCES plan_curricular(id),
    FOREIGN KEY (id_evidencia) REFERENCES archivo_evidencia(id),

    UNIQUE (id_objetivo, id_cohorte, periodo),
    CHECK (estado IN ('BORRADOR','VALIDADA')),
    CHECK (meta_porcentaje IS NULL OR meta_porcentaje BETWEEN 0 AND 100),
    CHECK (logro_porcentaje IS NULL OR logro_porcentaje BETWEEN 0 AND 100)
);

-- historial_estado_academico | Estados y condición apto, con vigencia temporal para F1/F4
CREATE TABLE historial_estado_academico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_egresado BIGINT NOT NULL,
    id_estado_academico BIGINT NOT NULL,
    apto_graduarse BOOLEAN,
